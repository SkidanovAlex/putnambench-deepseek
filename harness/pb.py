VERIFY_SH = """#!/usr/bin/env bash
# Pass/fail for one PutnamBench problem. Run from the benchmark directory.
set -uo pipefail
cd "$(dirname "$0")"
export PATH="$HOME/.elan/bin:$PATH"
exec python3 {pb} verify --bench "$PWD"
"""

README_MD = """# {name}

{tags}

## Problem

{informal}

## Task

`{name}.lean` contains a single Lean 4 theorem whose proof is `sorry`.
Replace the `sorry` with a real proof. {answer_task}

Mathlib is already built. To elaborate your file without the full check:

```bash
(cd {lean4} && lake env lean {dest}/{name}.lean)
```

Or just run `./verify.sh`, which does that and more.

## Rules

- Work ONLY inside this directory. Do not read, write, or reference any other
  benchmark directory, and do not modify anything under `{lean4}` -- that is
  the shared Mathlib project every other run uses.
- Do NOT change the theorem statement. `verify.sh` compares the statement
  against a frozen signature and fails if a hypothesis, binder or conclusion
  was altered, renamed or dropped.{answer_rule}
- No `sorry`, no `axiom`, no `native_decide`, no `@[implemented_by]`, no
  `@[extern]`. The only axioms your proof may depend on are `propext`,
  `Classical.choice` and `Quot.sound` (the Mathlib standard three).
- Helper lemmas above the theorem are fine, as long as they obey the rules.

`verify.sh` prints `PASS [{name}]` when the problem is solved.
"""


def cmd_stage(args) -> int:
    man = load_manifest()
    name = args.problem
    if name not in man:
        sys.exit(f"unknown problem: {name}")
    e = man[name]

    if args.variant == "wsolution":
        src = WSOL / f"{name}_sol.lean"
        if not src.exists():
            sys.exit(f"no wsolution source for {name} - run `pb.py prepare`")
    else:
        src = SRC / f"{name}.lean"

    dest = Path(args.dest).resolve()
    if dest.exists() and not args.force:
        sys.exit(f"{dest} exists (use --force)")
    dest.mkdir(parents=True, exist_ok=True)

    # The pristine sources carry the reference answer as a comment right under
    # the `abbrev` (and rewrite_solutions.py leaves that comment behind). Under
    # the `full` variant that comment IS the task, so strip it either way.
    text = src.read_text(encoding="utf8")
    if e["has_solution"] and e["reference_answer"]:
        ref = e["reference_answer"].strip()
        text = "".join(
            ln for ln in text.splitlines(keepends=True)
            if ln.strip().lstrip("-").strip() != ref)
    (dest / f"{name}.lean").write_text(text, encoding="utf8")

    vs = dest / "verify.sh"
    vs.write_text(VERIFY_SH.format(pb=HERE / "pb.py"))
    vs.chmod(0o755)

    if args.variant == "full" and e["has_solution"]:
        answer_task = (
            f"\n\nThis problem also has a factored answer: the "
            f"`abbrev {e['solution_name']}` at the top is `sorry` too. You "
            f"must supply the correct closed-form answer there AND prove the "
            f"theorem with it.")
        answer_rule = (
            f"\n- Do NOT change the type of `{e['solution_name']}`; it is "
            f"frozen the same way. Supply a value, not a `sorry`.")
    else:
        answer_task = "The answer, where the problem asks for one, is already inlined."
        answer_rule = ""

    (dest / "README.md").write_text(README_MD.format(
        name=name,
        tags=" ".join(f"`{t}`" for t in e["tags"]) or "(untagged)",
        informal=e["informal_statement"],
        lean4=LEAN4,
        dest=dest,
        answer_task=answer_task,
        answer_rule=answer_rule,
    ))

    (dest / ".pb.json").write_text(json.dumps(
        {"problem": name, "variant": args.variant}, indent=1))

    print(f"staged {name} ({args.variant}) -> {dest}")
    return 0


