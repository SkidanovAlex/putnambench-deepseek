def cmd_list(args) -> int:
    man = load_manifest()
    for name, e in sorted(man.items()):
        if args.year and e["year"] != args.year:
            continue
        if args.tag and args.tag not in e["tags"]:
            continue
        if args.with_answer and not e["has_solution"]:
            continue
        if args.no_answer and e["has_solution"]:
            continue
        if args.verbose:
            print(f"{name:24s} {'ANS' if e['has_solution'] else '   '} "
                  f"{','.join(e['tags'])}")
        else:
            print(name)
    return 0


def cmd_show(args) -> int:
    man = load_manifest()
    if args.problem not in man:
        sys.exit(f"unknown problem: {args.problem}")
    print(json.dumps(man[args.problem], indent=2, ensure_ascii=False))
    return 0


