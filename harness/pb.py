def fail(bench: str, msg: str) -> int:
    print(f"FAIL [{bench}] {msg}")
    return 1


def cmd_verify(args) -> int:
    bench = Path(args.bench).resolve()
    cfg_path = bench / ".pb.json"
    if not cfg_path.exists():
        sys.exit(f"{bench} is not a staged bench directory (no .pb.json)")
    cfg = json.loads(cfg_path.read_text())
    name, variant = cfg["problem"], cfg["variant"]
    man = load_manifest()
    e = man[name]

    f = bench / f"{name}.lean"
    if not f.exists():
        return fail(name, f"{name}.lean is missing")
    text = f.read_text(encoding="utf8")
    body = strip_comments(text)

    # ---- 1. textual escape hatches ---------------------------------------
    if re.search(r"\bsorry\b", body):
        return fail(name, "a 'sorry' remains")
    for pat, what in FORBIDDEN:
        if re.search(pat, body, re.MULTILINE):
            return fail(name, f"forbidden escape hatch ({what})")
    bad = [i for i in re.findall(r"^\s*import\s+(\S+)", body, re.MULTILINE)
           if i != "Mathlib"]
    if bad:
        return fail(name, f"unexpected import(s): {', '.join(bad)}")

    # ---- 2. the statement still says what it said ------------------------
    norm = normalize(text)
    sig = e["sig_wsolution"] if variant == "wsolution" else e["sig"]
    if sig is None:
        return fail(name, "no frozen signature for this variant")
    if sig not in norm:
        return fail(name, "the theorem statement was altered "
                          "(frozen signature not found)")

    # 2b. the statement's WORDS are unchanged; check its MEANING is too.
    #     Anything the pristine problem file already declared is part of the
    #     problem, not a rewrite of it.
    pristine = (WSOL / f"{name}_sol.lean" if variant == "wsolution"
                else SRC / f"{name}.lean")
    provided = (defined_names(pristine.read_text(encoding="utf8"))
                if pristine.exists() else set())
    shad = shadowing(text, sig, name, provided)
    if shad:
        return fail(name, "the proof redefines "
                          f"{', '.join(repr(s) for s in shad)}, which the frozen "
                          "statement depends on. The statement must keep its "
                          "Mathlib meaning -- do not shadow names it uses.")
    if variant == "full" and e["has_solution"]:
        if e["solution_sig"] not in norm:
            return fail(name, f"the type of {e['solution_name']} was altered")

    # ---- 3. it elaborates -------------------------------------------------
    names = [name]
    if variant == "full" and e["has_solution"]:
        names.append(e["solution_name"])
    check = bench / ".pb_check.lean"
    check.write_text(text.rstrip() + "\n\n"
                     + "".join(f"#print axioms {n}\n" for n in names))
    try:
        r = subprocess.run(
            ["lake", "env", "lean", str(check)],
            cwd=LEAN4, capture_output=True, text=True, timeout=LEAN_TIMEOUT)
    except subprocess.TimeoutExpired:
        check.unlink(missing_ok=True)
        return fail(name, f"lean timed out after {LEAN_TIMEOUT}s")
    out = (r.stdout or "") + (r.stderr or "")
    check.unlink(missing_ok=True)

    if r.returncode != 0 or re.search(r"^.*: error:", out, re.MULTILINE):
        print(out[-4000:])
        return fail(name, "the file does not elaborate")
    if "declaration uses 'sorry'" in out:
        return fail(name, "a declaration uses 'sorry'")

    # ---- 4. clean axioms --------------------------------------------------
    for n in names:
        m = re.search(r"'" + re.escape(n) + r"' depends on axioms: \[(.*?)\]",
                      out, re.DOTALL)
        if not m:
            if f"'{n}' does not depend on any axioms" in out:
                continue
            return fail(name, f"could not read `#print axioms {n}`")
        for ax in (a.strip() for a in m.group(1).split(",")):
            if ax and ax not in ALLOWED_AXIOMS:
                return fail(name, f"{n} depends on '{ax}'")

    print(f"PASS [{name}]")
    return 0


# --------------------------------------------------------------------------
# work queue
#
# One human-readable TSV, one row per problem. Every mutation takes an
# exclusive flock on a sidecar lock file and rewrites the table atomically
# (temp + os.replace), so any number of runners on this host can claim from
# it concurrently without stepping on each other. Rows are only ever mutated
# under that lock; readers (`queue-status`) take a shared lock.
#
# A runner that dies without releasing leaves its row `running`. `reap` puts
# such rows back to `todo` once the owning pid is gone or the claim is older
# than --stale-seconds -- the same failure we hit with the orphaned eolymp
# solver, handled here rather than left to a human.
# --------------------------------------------------------------------------

QUEUE = HERE / "problems.tsv"
QUEUE_COLS = ["problem", "variant", "status", "owner", "pid",
              "claimed_at", "finished_at", "steps", "note"]
STATUSES = {"todo", "running", "solved", "failed", "timeout", "skip",
            # The solver filed a Lean proof that the frozen statement is
            # FALSE. Terminal, but deliberately not "solved": nothing here
            # has checked the claim. A human reviews the artifacts under
            # putnambench/defects/ and then moves the row to skip (defect
            # confirmed) or todo (claim rejected).
            "disproved"}
# Only used for rows we CANNOT check by pid (no pid recorded, or a corrupt
# timestamp). A live worker is never reaped on age alone -- Lean runs are
# expected to last days, so an age-based steal would kill real work. Kept
# well beyond the solver's own per-problem timeout as a last-resort floor.
STALE_SECONDS = 5 * 24 * 3600


def queue_path() -> Path:
    return Path(os.environ.get("PB_QUEUE", QUEUE))


class _Lock:
    """flock on a sidecar; `shared=True` for readers."""

    def __init__(self, shared: bool = False):
        self.shared = shared
        self.fh = None

    def __enter__(self):
        import fcntl
        p = queue_path().with_suffix(queue_path().suffix + ".lock")
        p.parent.mkdir(parents=True, exist_ok=True)
        self.fh = open(p, "a+")
        fcntl.flock(self.fh,
                    fcntl.LOCK_SH if self.shared else fcntl.LOCK_EX)
        return self

    def __exit__(self, *exc):
        import fcntl
        fcntl.flock(self.fh, fcntl.LOCK_UN)
        self.fh.close()
        return False


def _now() -> str:
    import datetime
    return datetime.datetime.now(datetime.timezone.utc).isoformat(
        timespec="seconds")


def _read_rows() -> list[dict]:
    p = queue_path()
    if not p.exists():
        return []
    rows = []
    for i, line in enumerate(p.read_text().splitlines()):
        if not line.strip():
            continue
        parts = line.split("\t")
        if i == 0 and parts[0] == "problem":
            continue
        parts += [""] * (len(QUEUE_COLS) - len(parts))
        rows.append(dict(zip(QUEUE_COLS, parts[: len(QUEUE_COLS)])))
    return rows


def _write_rows(rows: list[dict]) -> None:
    p = queue_path()
    tmp = p.with_suffix(p.suffix + f".tmp.{os.getpid()}")
    body = ["\t".join(QUEUE_COLS)]
    body += ["\t".join((r.get(c) or "").replace("\t", " ").replace("\n", " ")
                       for c in QUEUE_COLS) for r in rows]
    tmp.write_text("\n".join(body) + "\n")
    os.replace(tmp, p)          # atomic; readers never see a partial table


def _pid_alive(pid: str) -> bool:
    try:
        os.kill(int(pid), 0)
        return True
    except (ValueError, ProcessLookupError):
        return False
    except PermissionError:
        return True


def _reap(rows: list[dict], stale_seconds: int) -> int:
    """Return abandoned `running` rows to `todo`.

    Liveness is decided by the owning PID, never by elapsed time: a Lean run
    is expected to take days, so reaping a live worker on age would hand its
    problem to a second worker and throw the first one's work away. Age is
    consulted ONLY for rows we cannot check -- no pid recorded, or a
    timestamp we cannot parse.
    """
    import datetime
    n, now = 0, datetime.datetime.now(datetime.timezone.utc)
    for r in rows:
        if r["status"] != "running":
            continue
        if r["pid"]:
            if _pid_alive(r["pid"]):
                continue                      # working; hands off
            why = "dead owner"
        else:
            try:
                age = (now - datetime.datetime.fromisoformat(
                    r["claimed_at"])).total_seconds()
            except ValueError:
                age = float("inf")
            if age <= stale_seconds:
                continue
            why = "no pid, stale"
        r.update(status="todo", owner="", pid="", claimed_at="",
                 note=f"reaped ({why})")
        n += 1
    return n


def cmd_queue_init(args) -> int:
    man = load_manifest()
    names = sorted(man)
    if args.year:
        names = [n for n in names if man[n]["year"] == args.year]
    if args.tag:
        names = [n for n in names if args.tag in man[n]["tags"]]
    if args.variant == "full":
        names = [n for n in names if man[n]["has_solution"]]
    if args.sample:
        import random
        rng = random.Random(args.seed)
        names = sorted(rng.sample(names, min(args.sample, len(names))))

    with _Lock():
        existing = {(r["problem"], r["variant"]): r for r in _read_rows()}
        rows, added = [], 0
        for n in names:
            key = (n, args.variant)
            if key in existing:
                rows.append(existing.pop(key))
                continue
            rows.append({"problem": n, "variant": args.variant,
                         "status": "todo", "owner": "", "pid": "",
                         "claimed_at": "", "finished_at": "", "steps": "",
                         "note": ""})
            added += 1
        if args.keep_others:
            rows += list(existing.values())
        rows.sort(key=lambda r: (r["problem"], r["variant"]))
        _write_rows(rows)
    print(f"queue {queue_path()}: {len(rows)} rows ({added} new)")
    return 0


def cmd_claim(args) -> int:
    """Atomically take one todo row. Prints `problem<TAB>variant`, or
    nothing with rc=1 when the queue is drained."""
    with _Lock():
        rows = _read_rows()
        if not rows:
            sys.exit("queue is empty - run `pb.py queue-init` first")
        _reap(rows, args.stale_seconds)
        pick = None
        for r in rows:
            if r["status"] != "todo":
                continue
            if args.variant and r["variant"] != args.variant:
                continue
            if args.problem and r["problem"] != args.problem:
                continue
            pick = r
            break
        if pick is None:
            _write_rows(rows)
            return 1
        pick.update(status="running", owner=args.owner,
                    pid=str(args.pid or os.getpid()), claimed_at=_now(),
                    finished_at="", steps="", note="")
        _write_rows(rows)
    print(f"{pick['problem']}\t{pick['variant']}")
    return 0


def cmd_release(args) -> int:
    if args.status not in STATUSES:
        sys.exit(f"bad status {args.status!r}; one of {sorted(STATUSES)}")
    with _Lock():
        rows = _read_rows()
        for r in rows:
            if r["problem"] == args.problem and (
                    not args.variant or r["variant"] == args.variant):
                r.update(status=args.status, finished_at=_now(),
                         steps=str(args.steps or ""), note=args.note or "",
                         pid="")
                break
        else:
            sys.exit(f"{args.problem} not in queue")
        _write_rows(rows)
    print(f"{args.problem} -> {args.status}")
    return 0


def cmd_reap(args) -> int:
    with _Lock():
        rows = _read_rows()
        n = _reap(rows, args.stale_seconds)
        _write_rows(rows)
    print(f"reaped {n} stale claim(s)")
    return 0


def cmd_requeue(args) -> int:
    """Put terminal rows back to `todo` for another attempt.

    `claim` only ever takes `todo`, so a failed problem is never retried
    automatically -- a fleet would otherwise spend days re-attempting the
    same wall. Retrying is therefore an explicit act: this is what turns a
    pass@1 sweep into pass@2.
    """
    if "solved" in args.status and not args.force:
        sys.exit("refusing to requeue solved rows without --force")
    with _Lock():
        rows = _read_rows()
        n = 0
        for r in rows:
            if r["status"] not in args.status:
                continue
            if args.problem and r["problem"] != args.problem:
                continue
            if args.variant and r["variant"] != args.variant:
                continue
            prev = r["status"]
            r.update(status="todo", owner="", pid="", claimed_at="",
                     finished_at="", steps="",
                     note=f"requeued from {prev}"
                          + (f" ({r['note'][:40]})" if r["note"] else ""))
            n += 1
        _write_rows(rows)
    print(f"requeued {n} row(s) -> todo")
    return 0


def cmd_queue_status(args) -> int:
    with _Lock(shared=True):
        rows = _read_rows()
    by = collections_counter(r["status"] for r in rows)
    total = len(rows)
    done = by.get("solved", 0)
    print(f"{queue_path()}  {total} problems")
    for s in ["solved", "failed", "timeout", "disproved", "running", "todo",
              "skip"]:
        if by.get(s):
            print(f"  {s:8s} {by[s]:5d}")
    attempted = by.get("solved", 0) + by.get("failed", 0) + by.get("timeout", 0)
    if attempted:
        print(f"  solve rate: {done}/{attempted} attempted "
              f"= {100.0 * done / attempted:.1f}%")
    if args.verbose:
        print()
        for r in rows:
            if args.status and r["status"] != args.status:
                continue
            print(f"  {r['problem']:22s} {r['variant']:10s} {r['status']:8s} "
                  f"{r['owner']:20s} {r['note'][:40]}")
    return 0


def collections_counter(it):
    import collections
    return collections.Counter(it)


