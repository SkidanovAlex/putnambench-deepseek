#!/usr/bin/env python3
"""pb.py - PutnamBench harness for the curric lean solver.

One shared lake project (`../lean4`, with Mathlib already built) serves all
672 problems. Each run gets its own bench directory holding exactly ONE .lean
file, so an agent working from that directory cannot see or edit its
neighbours. Verification elaborates the single file with `lake env lean`
against the shared project -- no per-problem lake project, no re-fetch of
Mathlib.

Commands
    prepare                       build manifest.json from the pristine sources
    list [filters]                list problem names
    show <problem>                print manifest entry
    stage <problem> --dest DIR    create a bench directory
    verify --bench DIR            pass/fail one bench directory
    selftest                      check the checker against a synthetic problem

Work queue (see the "work queue" section below; used by run_putnam_solver.py)
    queue-init [filters]          create/extend problems.tsv
    claim --owner NAME            atomically take one todo row
    release <problem> --status S  record the outcome
    reap                          return abandoned claims to todo
    queue-status [-v]             counts, and optionally every row

Variants
    wsolution   the reference answer is inlined into the statement; the agent
                only writes a proof. This is what the leaderboard reports.
    full        the `abbrev <name>_solution := sorry` is left in place; the
                agent must produce the answer AND the proof.
Problems with no `abbrev` are identical under both variants.
"""

from __future__ import annotations

