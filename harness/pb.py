def cmd_prepare(args) -> int:
    if not SRC.is_dir():
        sys.exit(f"missing {SRC}")

    # Generate the wsolution variant with the upstream script, so our inlining
    # matches what everyone else reports against.
    script = LEAN4 / "scripts" / "rewrite_solutions.py"
    print(f"running {script.relative_to(ROOT)} ...")
    r = subprocess.run([sys.executable, str(script)], cwd=LEAN4,
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout[-2000:], r.stderr[-2000:], file=sys.stderr)
        sys.exit("rewrite_solutions.py failed")
    print(f"  wrote {len(list(WSOL.glob('*.lean')))} files to "
          f"{WSOL.relative_to(ROOT)}")

    informal = {e["problem_name"]: e for e in json.loads(INFORMAL.read_text())}

    entries, skipped = {}, []
    for f in sorted(SRC.glob("*.lean")):
        name = f.stem
        text = f.read_text(encoding="utf8")
        try:
            sig = extract_theorem_sig(text, name)
        except ValueError as e:
            skipped.append(f"{name}: {e}")
            continue

        ab = extract_abbrev(text)
        wfile = WSOL / f"{name}_sol.lean"
        sig_w = None
        if wfile.exists():
            try:
                sig_w = extract_theorem_sig(
                    wfile.read_text(encoding="utf8"), name)
            except ValueError as e:
                skipped.append(f"{name} (wsolution): {e}")

        inf = informal.get(name, {})
        m = re.match(r"putnam_(\d{4})_([ab]\d+)$", name)
        entries[name] = {
            "name": name,
            "year": int(m.group(1)) if m else None,
            "index": m.group(2) if m else None,
            "tags": inf.get("tags", []),
            "informal_statement": inf.get("informal_statement", ""),
            "informal_solution": inf.get("informal_solution", "None."),
            "has_solution": ab is not None,
            "solution_name": ab[1] if ab else None,
            "solution_type": ab[2] if ab else None,
            "solution_sig": ab[0] if ab else None,
            "reference_answer": ab[3] if ab else None,
            "sig": sig,
            "sig_wsolution": sig_w,
            "src_sha256": sha256(f),
        }

    manifest_path().write_text(json.dumps(entries, indent=1, ensure_ascii=False))
    n_sol = sum(1 for e in entries.values() if e["has_solution"])
    print(f"manifest: {len(entries)} problems ({n_sol} with a factored answer)"
          f" -> {MANIFEST.relative_to(ROOT)}")
    if skipped:
        print(f"skipped {len(skipped)}:", file=sys.stderr)
        for s in skipped[:20]:
            print("  " + s, file=sys.stderr)
    return 0


def manifest_path() -> Path:
    """The manifest, overridable via PB_MANIFEST (used by `selftest`)."""
    return Path(os.environ.get("PB_MANIFEST", MANIFEST))


def load_manifest() -> dict:
    p = manifest_path()
    if not p.exists():
        sys.exit(f"no {p.name} - run `pb.py prepare` first")
    return json.loads(p.read_text())


