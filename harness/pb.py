SRC = LEAN4 / "src"                   # pristine statements (never modified)
WSOL = LEAN4 / "solutions_replaced_new"   # generated by rewrite_solutions.py
INFORMAL = ROOT / "informal" / "putnam.json"
MANIFEST = HERE / "manifest.json"

ALLOWED_AXIOMS = {"propext", "Classical.choice", "Quot.sound"}

# Textual escape hatches. `sorry` is handled separately (better message).
FORBIDDEN = [
    (r"\bsorryAx\b", "sorryAx"),
    (r"^\s*axiom\s", "axiom declaration"),
    (r"\bnative_decide\b", "native_decide"),
    (r"@\[\s*implemented_by", "@[implemented_by]"),
    (r"@\[\s*extern", "@[extern]"),
]

LEAN_TIMEOUT = int(os.environ.get("PB_LEAN_TIMEOUT", "1800"))


# --------------------------------------------------------------------------
# text utilities
# --------------------------------------------------------------------------

def strip_comments(text: str) -> str:
    """Remove -- line comments and (nesting-aware) /- -/ block comments.

    Docstrings (/-- -/) are block comments and go too; every frozen signature
    starts at the `theorem`/`abbrev` keyword, so nothing we compare is lost.
    """
    out = []
    i, n, depth = 0, len(text), 0
    while i < n:
        if text.startswith("/-", i):
            depth += 1
            i += 2
        elif text.startswith("-/", i) and depth:
            depth -= 1
            i += 2
        elif depth:
            i += 1
        elif text.startswith("--", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


def normalize(text: str) -> str:
    """Comment-free, whitespace-collapsed form used for signature matching."""
    return re.sub(r"\s+", " ", strip_comments(text)).strip()


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


# --------------------------------------------------------------------------- #
# shadowing guard
#
# The signature check above is TEXTUAL, so it cannot see a proof that leaves the
# statement byte-identical while redefining what a name in it MEANS. Caught in
# formalbench (minif2f__imo_2006_p3):
#
#     namespace imo_2006_p3
#     def IsLeast (s : Set ℝ) (a : ℝ) : Prop := a ∈ s
#
# Mathlib's `IsLeast s a` also requires `a` to be a lower bound, so dropping that
# conjunct throws away the whole problem -- and the file still elaborates, has no
# `sorry`, and depends on no extra axioms. Deliberately duplicated from
# formalbench/harness/fb.py rather than imported: this file is the verifier for a
# running fleet and must not break if that directory moves.
# --------------------------------------------------------------------------- #

DEFINES_RE = re.compile(
    r"^\s*(?:@\[[^\]]*\]\s*)?(?:noncomputable\s+|private\s+|protected\s+|scoped\s+|local\s+)*"
    r"(def|abbrev|structure|inductive|class|instance|notation|macro|syntax)\s+"
    r"([A-Za-z_][A-Za-z0-9_'.]*)", re.MULTILINE)

IDENT_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_'.]*")


def defined_names(text: str) -> set:
    """Global names a file declares (last component only: `Complex.abs` -> `abs`)."""
    return {n.split(".")[-1] for _, n in DEFINES_RE.findall(strip_comments(text))}


def sig_binders(sig: str) -> set:
    """Names BOUND inside the statement -- binders, not globals.

    `theorem t : ∃ f : ℕ → ℕ, ...` binds `f`, so a helper `def f` beside the
    theorem shadows nothing. Without this every such helper is a false positive.
    """
    out = set()
    for grp in re.findall(r"[({\[⦃]\s*([^:()\[\]{}⦃⦄]+?)\s*:", sig):
        out.update(IDENT_RE.findall(grp))
    for grp in re.findall(r"[∀∃]\s*([^,:]+)[,:]", sig):
        out.update(IDENT_RE.findall(grp))
    for grp in re.findall(r"\bfun\s+([^=]+?)(?:=>|↦)", sig):
        out.update(IDENT_RE.findall(grp))
    return out


def shadowing(text: str, sig: str, thm: str, provided: set) -> list:
    """Names `text` redefines that also occur free in the frozen statement."""
    allowed = set(provided) | {thm}
    bound = sig_binders(sig)
    sig_idents = {t.split(".")[-1] for t in IDENT_RE.findall(sig)}
    return sorted(n for n in defined_names(text)
                  if n in sig_idents and n not in bound and n not in allowed
                  and not n.endswith("_solution"))


def extract_theorem_sig(text: str, name: str) -> str:
    """`theorem <name> ... :=` with the proof removed, normalized.

    Statement-internal `:=` (from `let`, structure instances) all precede the
    one that introduces the proof, so taking the last is correct on pristine
    sources, where the proof is exactly `sorry`.
    """
    body = strip_comments(text)
    m = re.search(r"\btheorem\s+" + re.escape(name) + r"\b", body)
    if not m:
        raise ValueError(f"no `theorem {name}` in source")
    tail = body[m.start():]
    cut = tail.rfind(":=")
    if cut < 0:
        raise ValueError(f"no `:=` after `theorem {name}`")
    return normalize(tail[: cut + 2])


def extract_abbrev(text: str) -> tuple[str, str, str, str] | None:
    """(sig, name, type, reference answer) for a factored-solution problem."""
    for m in re.finditer(
        r"^(?:noncomputable\s+)?abbrev\s+(\S+)\s*:\s*(.*?):=\s*sorry\s*$",
        text,
        re.MULTILINE,
    ):
        name, typ = m.group(1), m.group(2).strip()
        rest = text[m.end():].lstrip("\n")
        answer = ""
        if rest.startswith("--"):
            answer = rest.split("\n", 1)[0][2:].strip()
        return normalize(m.group(0)[: m.group(0).rfind(":=") + 2]), name, typ, answer
    return None


