SELFTEST_STMT = """import Mathlib

/-- Self-test: a stand-in for a Putnam statement. -/
theorem pb_selftest (n : ℕ) (h : 2 ≤ n) : 1 < n :=
"""

SELFTEST_CASES = [
    ("pristine stub", SELFTEST_STMT + "sorry\n", False, "a 'sorry' remains"),
    ("real proof", SELFTEST_STMT + "by omega\n", True, None),
    ("weakened statement",
     SELFTEST_STMT.replace("2 ≤ n) : 1 < n", "3 ≤ n) : 1 < n") + "by omega\n",
     False, "statement was altered"),
    ("frozen signature hidden in a comment",
     "import Mathlib\n\n-- theorem pb_selftest (n : ℕ) (h : 2 ≤ n) : 1 < n :=\n"
     "theorem pb_selftest (n : ℕ) (h : 3 ≤ n) : 1 < n :=\nby omega\n",
     False, "statement was altered"),
    ("axiom escape hatch",
     "import Mathlib\n\naxiom cheat : ∀ n : ℕ, 1 < n\n\n"
     + SELFTEST_STMT + "cheat n\n",
     False, "forbidden escape hatch"),
]


def cmd_selftest(args) -> int:
    import tempfile
    from types import SimpleNamespace

    tmp = Path(tempfile.mkdtemp(prefix="pb_selftest_"))
    man_path = tmp / "manifest.json"
    entry = {
        "name": "pb_selftest", "year": None, "index": None, "tags": [],
        "informal_statement": "", "informal_solution": "None.",
        "has_solution": False, "solution_name": None, "solution_type": None,
        "solution_sig": None, "reference_answer": None,
        "sig": extract_theorem_sig(SELFTEST_STMT + "sorry\n", "pb_selftest"),
        "sig_wsolution": extract_theorem_sig(SELFTEST_STMT + "sorry\n",
                                             "pb_selftest"),
        "src_sha256": "",
    }
    man_path.write_text(json.dumps({"pb_selftest": entry}))
    os.environ["PB_MANIFEST"] = str(man_path)

    bench = tmp / "bench"
    bench.mkdir()
    (bench / ".pb.json").write_text(
        json.dumps({"problem": "pb_selftest", "variant": "wsolution"}))

    ok = True
    for label, content, want_pass, want_msg in SELFTEST_CASES:
        (bench / "pb_selftest.lean").write_text(content)
        rc = cmd_verify(SimpleNamespace(bench=str(bench)))
        got_pass = (rc == 0)
        good = got_pass == want_pass
        print(f"  {'ok  ' if good else 'BAD '} {label}: "
              f"{'PASS' if got_pass else 'FAIL'} (expected "
              f"{'PASS' if want_pass else 'FAIL: ' + want_msg})")
        ok &= good

    shutil.rmtree(tmp, ignore_errors=True)
    print("selftest:", "OK" if ok else "FAILED")
    return 0 if ok else 1


